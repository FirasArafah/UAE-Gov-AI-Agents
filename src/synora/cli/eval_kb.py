"""Measure knowledge base retrieval against the test set in data/kb_eval_questions.json.

No answers are generated, so this needs only the embedding model and takes a few minutes.
Each question runs through the agent that would answer it, which is what answers are built on.
Questions with their own wording also run as a plain search, which is what the Knowledge base
page does. Prints a Markdown report: hit rates per group and every question that missed.

Usage: python -m synora.cli.eval_kb [--questions data/kb_eval_questions.json] [--top-k 8]
"""

import argparse
import asyncio
import json
import re
from pathlib import Path
from types import SimpleNamespace

from synora.agents.base import BaseAgent
from synora.config import settings
from synora.rag.retriever import PgVectorRetriever

QUESTIONS_PATH = Path("data/kb_eval_questions.json")
SCENARIO_PATH = Path("data/scenarios/golden_gate.json")


def matches(hit: dict, expected: dict) -> bool:
    """A retrieved excerpt satisfies an expected source when every given field agrees."""
    if expected["title"] not in (hit.get("title") or ""):
        return False
    if "section" in expected and not re.search(expected["section"], hit.get("section") or ""):
        return False
    # PDF text breaks lines anywhere, so a phrase may span a line break.
    text = " ".join((hit.get("content") or "").split()).lower()
    return "text" not in expected or expected["text"].lower() in text


def first_rank(hits: list[dict], expected: list[dict]) -> int | None:
    """1-based rank of the first excerpt matching any expected source."""
    for rank, hit in enumerate(hits, start=1):
        if any(matches(hit, e) for e in expected):
            return rank
    return None


def score(question: dict, hits: list[dict]) -> dict:
    """Result of one question: found at all, its rank, and what is missing."""
    if "expect_all" in question:
        missing = [e for e in question["expect_all"] if first_rank(hits, [e]) is None]
        return {"found": not missing, "rank": None, "missing": missing}
    rank = first_rank(hits, question["expect"])
    found = rank is not None and (rank == 1 or not question.get("first"))
    return {"found": found, "rank": rank, "missing": [] if found else question["expect"]}


def summarize(results: list[dict]) -> dict:
    """Hit rates over a list of scored results."""
    ranked = [r for r in results if r["rank"] is not None or "expect_all" not in r["question"]]
    ranks = [r["rank"] for r in ranked if r["rank"] is not None]
    count = len(ranked) or 1
    return {
        "questions": len(results),
        "found": sum(r["found"] for r in results),
        "hit_at_1": sum(rank == 1 for rank in ranks) / count,
        "hit_at_3": sum(rank <= 3 for rank in ranks) / count,
        "mrr": sum(1 / rank for rank in ranks) / count,
    }


async def run(path: Path, top_k: int) -> list[dict]:
    data = json.loads(path.read_text(encoding="utf-8"))
    events = {
        e["sequence"]: e["content"]
        for e in json.loads(SCENARIO_PATH.read_text(encoding="utf-8"))["events"]
    }
    retriever = PgVectorRetriever()
    settings.rag_top_k = top_k
    results = []
    for question in data["questions"]:
        query = events[question["event"]] if "event" in question else question["q"]
        slug = question["agent"]
        record = SimpleNamespace(role=slug, slug=slug, name=slug, system_prompt="")
        hits = await BaseAgent(record, None, retriever)._retrieve(query)
        result = {"question": question, "query": query, "hits": hits, **score(question, hits)}
        if "q" in question:
            plain = await retriever.search(query, top_k=top_k)
            result["plain"] = {"question": question, **score(question, plain)}
        results.append(result)
    return results


def percent(value: float) -> str:
    return f"{value * 100:.0f}%"


def report(results: list[dict], top_k: int) -> str:
    groups: dict[str, list[dict]] = {}
    for result in results:
        groups.setdefault(result["question"]["group"], []).append(result)

    total = summarize(results)
    plain = summarize([r["plain"] for r in results if "plain" in r])
    lines = [
        "# Knowledge base retrieval evaluation",
        "",
        "Generated by `make eval-kb` from `data/kb_eval_questions.json`. The expected source of",
        "each question was checked against the document text. No answers are generated: this",
        "measures only whether retrieval brings back the right passage.",
        "",
        f"**{total['found']} of {total['questions']} questions passed** through the agent that "
        f"would answer them, with {top_k} excerpts per query. First-result rate "
        f"{percent(total['hit_at_1'])}, top-3 rate {percent(total['hit_at_3'])}.",
        "",
        f"As a plain search across all documents (the Knowledge base page), {plain['found']} of "
        f"{plain['questions']} passed. First-result rate {percent(plain['hit_at_1'])}, top-3 rate "
        f"{percent(plain['hit_at_3'])}.",
        "",
        "An agency's retrieval always puts the article that sets its position first, which lowers "
        "its first-result rate on questions about other articles.",
        "",
        "| Group | Passed | First result | Top 3 | MRR |",
        "|---|---:|---:|---:|---:|",
    ]
    for name, group in groups.items():
        s = summarize(group)
        lines.append(
            f"| {name} | {s['found']}/{s['questions']} | {percent(s['hit_at_1'])} | "
            f"{percent(s['hit_at_3'])} | {s['mrr']:.2f} |"
        )

    missed = [r for r in results if not r["found"]]
    lines += ["", "## Questions that did not pass", ""]
    if not missed:
        lines.append("None.")
    for result in missed:
        question = result["question"]
        wanted = "; ".join(" / ".join(str(v) for v in e.values()) for e in result["missing"])
        got = ", ".join(
            f"{(h.get('title') or '')[:24]} [{h.get('section')}]" for h in result["hits"][:4]
        )
        lines.append(f"- `{question['id']}`: expected {wanted}. Retrieved first: {got}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--questions", type=Path, default=QUESTIONS_PATH)
    parser.add_argument("--top-k", type=int, default=settings.rag_top_k)
    args = parser.parse_args()
    results = asyncio.run(run(args.questions, args.top_k))
    print(report(results, args.top_k), end="")


if __name__ == "__main__":
    main()
